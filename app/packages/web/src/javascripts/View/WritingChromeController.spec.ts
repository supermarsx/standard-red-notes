import { WritingChromeController } from './WritingChromeController'

beforeEach(() => jest.useFakeTimers())
afterEach(() => jest.useRealTimers())
it('steps from full through compact to minimal after losing focus, without typing postponing it', () => {
  const changed = jest.fn()
  const controller = new WritingChromeController(changed)
  controller.focus()
  controller.release()
  jest.advanceTimersByTime(4000)
  controller.release()
  expect(changed).not.toHaveBeenCalled()
  jest.advanceTimersByTime(1000)
  expect(changed).toHaveBeenLastCalledWith('compact')
  jest.advanceTimersByTime(5000)
  expect(changed).toHaveBeenLastCalledWith('minimal')
  controller.focus()
  expect(changed).toHaveBeenLastCalledWith('full')
  controller.dispose()
})
it('expands only after two seconds of hover and restores the earlier step two seconds after leaving', () => {
  const changed = jest.fn()
  const controller = new WritingChromeController(changed)
  controller.release()
  jest.advanceTimersByTime(10000)
  controller.hoverStart()
  jest.advanceTimersByTime(1999)
  expect(changed).toHaveBeenLastCalledWith('minimal')
  jest.advanceTimersByTime(1)
  expect(changed).toHaveBeenLastCalledWith('full')
  controller.hoverEnd()
  jest.advanceTimersByTime(1999)
  expect(changed).toHaveBeenLastCalledWith('full')
  jest.advanceTimersByTime(1)
  expect(changed).toHaveBeenLastCalledWith('minimal')
  controller.dispose()
})
it('cancels short hover, protects focused controls, and disposes all pending transitions', () => {
  const changed = jest.fn()
  const controller = new WritingChromeController(changed)
  controller.hoverStart()
  jest.advanceTimersByTime(500)
  controller.hoverEnd()
  controller.focus()
  jest.advanceTimersByTime(10000)
  expect(changed).not.toHaveBeenCalled()
  controller.release()
  controller.dispose()
  jest.runAllTimers()
  expect(changed).not.toHaveBeenCalled()
})
